CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA extensions;

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) NOT NULL UNIQUE,
    password varchar(128) NOT NULL,
    display_name text NOT NULL,
    reputation integer NOT NULL DEFAULT 0,
    role text NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'moderator', 'admin')),
    is_active boolean NOT NULL DEFAULT true,
    is_staff boolean NOT NULL DEFAULT false,
    is_superuser boolean NOT NULL DEFAULT false,
    date_joined timestamptz NOT NULL DEFAULT now(),
    last_login timestamptz
);

CREATE TABLE plants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    common_name text NOT NULL,
    scientific_name text NOT NULL DEFAULT '',
    description text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved')),
    created_by_id bigint REFERENCES users (id) ON DELETE SET NULL,
    best_submission_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    plant_id bigint NOT NULL REFERENCES plants (id),
    location extensions.geometry(Point, 4326) NOT NULL,
    bloom_start date NOT NULL,
    bloom_end date NOT NULL,
    description text NOT NULL DEFAULT '',
    photo_key text NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'changes_requested', 'rejected')),
    revision integer NOT NULL DEFAULT 1 CHECK (revision >= 1),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT submissions_bloom_dates_check CHECK (bloom_end >= bloom_start)
);

ALTER TABLE plants
    ADD CONSTRAINT plants_best_submission_fk
    FOREIGN KEY (best_submission_id)
    REFERENCES submissions (id)
    ON DELETE SET NULL;

CREATE TABLE plant_edits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id bigint NOT NULL REFERENCES plants (id),
    user_id bigint NOT NULL REFERENCES users (id),
    proposed_changes jsonb NOT NULL
        CHECK (jsonb_typeof(proposed_changes) = 'object'),
    reason text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'changes_requested', 'rejected')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE moderation_review (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reviewer_id bigint NOT NULL REFERENCES users (id),
    submission_id bigint REFERENCES submissions (id),
    submission_revision integer,
    plant_edit_id bigint REFERENCES plant_edits (id),
    decision text NOT NULL
        CHECK (decision IN ('approve', 'request_changes', 'reject')),
    comment text,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT moderation_review_one_target_check
        CHECK ((submission_id IS NOT NULL) <> (plant_edit_id IS NOT NULL)),
    CONSTRAINT moderation_review_revision_check
        CHECK (
            (submission_id IS NULL AND submission_revision IS NULL)
            OR (
                submission_id IS NOT NULL
                AND submission_revision IS NOT NULL
                AND submission_revision >= 1
            )
        ),
    CONSTRAINT moderation_review_comment_check
        CHECK (
            decision <> 'request_changes'
            OR NULLIF(BTRIM(comment), '') IS NOT NULL
        )
);

CREATE TABLE reputation_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES users (id),
    delta integer NOT NULL,
    reason text NOT NULL
        CHECK (
            reason IN (
                'submission_approved',
                'submission_rejected',
                'edit_approved',
                'edit_rejected',
                'review_completed',
                'admin_adjustment'
            )
        ),
    review_id bigint REFERENCES moderation_review (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT reputation_events_review_check
        CHECK ((reason = 'admin_adjustment') = (review_id IS NULL))
);

CREATE INDEX plants_created_by_id_idx
    ON plants (created_by_id);
CREATE INDEX plants_best_submission_id_idx
    ON plants (best_submission_id);
CREATE INDEX submissions_user_id_idx
    ON submissions (user_id);
CREATE INDEX submissions_plant_id_idx
    ON submissions (plant_id);
CREATE INDEX submissions_status_idx
    ON submissions (status);
CREATE INDEX submissions_location_idx
    ON submissions USING gist (location);
CREATE INDEX plant_edits_plant_id_idx
    ON plant_edits (plant_id);
CREATE INDEX plant_edits_user_id_idx
    ON plant_edits (user_id);
CREATE INDEX plant_edits_status_idx
    ON plant_edits (status);
CREATE INDEX moderation_review_reviewer_id_idx
    ON moderation_review (reviewer_id);
CREATE INDEX moderation_review_submission_id_idx
    ON moderation_review (submission_id);
CREATE INDEX moderation_review_plant_edit_id_idx
    ON moderation_review (plant_edit_id);
CREATE INDEX reputation_events_user_id_idx
    ON reputation_events (user_id);
CREATE INDEX reputation_events_review_id_idx
    ON reputation_events (review_id);

CREATE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER plants_set_updated_at
    BEFORE UPDATE ON plants
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER submissions_set_updated_at
    BEFORE UPDATE ON submissions
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE TRIGGER plant_edits_set_updated_at
    BEFORE UPDATE ON plant_edits
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

